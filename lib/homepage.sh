# The Homepage dashboard: settings.yaml, widgets.yaml and services.yaml.
# Sourced by configure.sh, which loads .env, defines the URL constants
# and the log/ok/skip/die helpers.
#
# settings.yaml and widgets.yaml are generated on every run so the layout
# follows the tiles. To take one over, put "# keep" on its first line and it
# is never touched again. (Homepage writes stock templates into an empty
# config directory on first start; those are replaced too.) services.yaml
# carries API keys and is written fresh every run; every tile has a
# siteMonitor on its internal address, which gives the status dot.

# ---------------------------------------------------------------- Homepage
# "/* keep */" as well as "# keep", because custom.css is CSS and a bare
# "# keep" on line 1 is a parse error that would eat the first rule after it.
homepage_keep() { [[ -f "$1" ]] && head -n1 "$1" | grep -qxE '# keep|/\* keep \*/'; }
homepage_news_slug() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9\n' '-' | sed 's/-\{2,\}/-/g; s/^-//; s/-$//'; }

# Which resource block the archive disk is, counting from 1. The widget renders
# cpu, then memory, then the disks in the order widgets.yaml lists them, so the
# number depends on what that file turned on - which is why it is read back out
# of the generated file rather than written down twice and left to drift.
homepage_archive_resource_index() {   # homepage_archive_resource_index DIR
  local f=$1/widgets.yaml
  [[ -f "$f" ]] || return 1
  awk '
    /^- resources:/ { inres = 1; next }
    /^- /           { inres = 0 }
    !inres          { next }
    /cpu: true/     { n++ }
    /memory: true/  { n++ }
    /^ *disk: *\//  { n++; if ($0 ~ /\/data\/archive\/media$/) { print n; found = 1; exit } }
    /^ *- *\//      { n++; if ($0 ~ /\/data\/archive\/media$/) { print n; found = 1; exit } }
    END             { if (!found) exit 1 }
  ' "$f"
}

homepage_custom_css() {           # homepage_custom_css DIR
  local dir=$1 cloud nth
  if homepage_keep "$dir/custom.css"; then
    skip "custom.css (kept)"
    return 0
  fi
  nth=$(homepage_archive_resource_index "$dir" 2>/dev/null) || nth=""
  # A Feather-style cloud, stroked, used as a mask rather than as an image: the
  # mask takes the alpha and background-color paints it, so the glyph follows
  # the theme instead of being a fixed colour.
  cloud="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='%23000' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'%3E%3Cpath d='M18 10h-1.26A8 8 0 1 0 9 20h9a5 5 0 0 0 0-10z'/%3E%3C/svg%3E"
  {
    echo "/* Generated by configure.sh - see the next line to take it over. */"
    echo "/* keep   <- make that line 1, comment markers and all, and this file is yours. */"
    if archive_enabled && [[ -n "$nth" ]]; then
      cat <<CSS

/* The archive is the last disk in the resources widget. That widget takes no
   icon: key of its own - icons belong to services, which is how the Archive
   tile gets its mdi-cloud-lock-outline - so the drive glyph is masked into a
   cloud here instead. The <svg> itself is masked rather than replaced, which
   keeps its w-5 h-5 sizing and its text-theme classes, so currentColor goes on
   following light and dark. Only written while the tier is on: with it off the
   last disk is /data, and a cloud over the local disk would be a lie. */
#widgets-wrap .information-widget-resource:nth-child($nth) .resource-icon > * { display: none; }
#widgets-wrap .information-widget-resource:nth-child($nth) .resource-icon {
  background-color: currentColor;
  -webkit-mask: url("$cloud") center / contain no-repeat;
          mask: url("$cloud") center / contain no-repeat;
}
CSS
    fi
  } > "$dir/custom.css"
  if archive_enabled && [[ -n "$nth" ]]; then
    ok "custom.css (cloud glyph on resource $nth, the archive disk)"
  elif archive_enabled; then
    ok "custom.css (no cloud: could not place the archive disk in widgets.yaml)"
  else
    ok "custom.css"
  fi
}

# Columns that leave no tile alone on the last row. Three where it divides,
# four or two where it does not: seven tiles over three columns strand one,
# which is the arithmetic Infrastructure below already carries by hand.
homepage_columns() {              # homepage_columns TILE_COUNT
  local n=${1:-0} c
  (( n > 0 )) || { printf 3; return 0; }
  (( n <= 3 )) && { printf '%d' "$n"; return 0; }
  for c in 3 4 2; do (( n % c != 1 )) && { printf '%d' "$c"; return 0; }; done
  printf 3
}

# How many headline tiles NEWS_FEEDS will actually produce - the same test the
# tile loop applies, so the column count matches what gets rendered.
homepage_news_count() {
  local entries entry title url n=0
  IFS=';' read -ra entries <<<"${NEWS_FEEDS:-}"
  for entry in "${entries[@]}"; do
    title=${entry%%|*}; url=${entry#*|}
    [[ -n "$title" && "$url" == http* ]] && n=$(( n + 1 ))
  done
  printf '%d' "$n"
}

homepage_settings_yaml() {        # homepage_settings_yaml DIR RECENTLY_ADDED INFRASTRUCTURE
  local dir=$1 recent=$2 infra=$3
  if homepage_keep "$dir/settings.yaml"; then
    skip "settings.yaml (# keep)"
  else
    # The layout only names groups services.yaml will actually carry: without a
    # Plex token there is nothing recently added. Infrastructure is always there
    # - Recyclarr, FlareSolverr and the Docker proxy need no configuration.
    {
      cat <<YAML
# Generated by configure.sh - put "# keep" on this line to make it yours.
title: Media
language: en
headerStyle: clean
hideVersion: true
statusStyle: dot
# No showStats anywhere, on purpose. Homepage keeps no memory of a folded tile
# - the open state is seeded from showStats on every page load - so "open by
# default" means the stats come back on every refresh, and in settings.yaml it
# is worse still: there it forces them open and the fold click cannot close
# them at all. Without it the dashboard stays compact and a status dot expands
# the container it belongs to for as long as you are looking at it.
quicklaunch:
  searchDescriptions: true
  hideInternetSearch: true
  hideVisitURL: true
layout:
  Media:
    style: row
    columns: 2
YAML
      # Three: Films, Series and Music where there is a music library, two where
      # there is not, and neither leaves a tile stranded on a row of its own.
      [[ "$recent" == yes ]] && cat <<YAML
  Recently added:
    style: row
    columns: 3
YAML
      cat <<YAML
  Today:
    style: row
    columns: $(homepage_columns $(( 3 + $(homepage_news_count) )))
  Downloads:
    style: row
    columns: 2
  Automation:
    style: row
    columns: 3
YAML
      [[ "$infra" == yes ]] && cat <<YAML
  Infrastructure:
    style: row
    # Four, not three: seven tiles over three columns leave one stranded on a
    # row of its own. Over four they fall 4 + 3, and because the four without
    # statistics come first the two rows also end up the same height.
    columns: 4
YAML
    } > "$dir/settings.yaml"
    ok "settings.yaml"
  fi
}

