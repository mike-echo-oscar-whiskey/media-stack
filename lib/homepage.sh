homepage_tiles_infrastructure() {
  echo "- Infrastructure:"
  # No web interface to link to; the tile is there for its container state,
  # which is the only thing there is to know about them.
  cat <<YAML
    - Alerts:
        href: $(yq "http://ntfy.$d/${NTFY_TOPIC:-}")
        icon: ntfy.png
        description: failures worth knowing about
        server: my-docker
        container: ntfy
        siteMonitor: http://ntfy/v1/health
    - Recyclarr:
        icon: mdi-tune-vertical
        description: TRaSH Guides sync
        server: my-docker
        container: recyclarr
    - FlareSolverr:
        icon: mdi-shield-key-outline
        description: indexer challenges
        server: my-docker
        container: flaresolverr
    - Docker proxy:
        icon: mdi-docker
        description: container state for this dashboard
        server: my-docker
        container: dockerproxy
YAML
  # Gluetun's control API answers the public-IP and port routes without a
  # key (its auth.toml, written by setup.sh); /v1/portforward is the
  # post-3.40 route, hence widget version 2.
  cat <<YAML
    - VPN:
        icon: gluetun.png
        server: my-docker
        container: gluetun
        description: torrent traffic exit
        siteMonitor: http://gluetun:8000/v1/publicip/ip
        widget:
          type: gluetun
          url: http://gluetun:8000
          version: 2
          fields: ["public_ip", "country", "port_forwarded"]
YAML
  local ph_url ph_pw ph_label
  for n in "" 2; do
    ph_url=$(eval "printf '%s' \"\${PIHOLE${n}_URL:-}\"")
    [[ -n "$ph_url" ]] || continue
    ph_pw=$(eval "printf '%s' \"\${PIHOLE${n}_PASSWORD:-}\"")
    ph_label=$(eval "printf '%s' \"\${PIHOLE${n}_LABEL:-}\"")
    cat <<YAML
    - $(yq "${ph_label:-Pi-hole}"):
        href: $(yq "$ph_url/admin/")
        icon: pi-hole.png
        # ping, not siteMonitor: siteMonitor is hardcoded to HEAD (Homepage
        # 2.4.0 has no method option), and Pi-hole v6 answers HEAD with 405 plus
        # framing that the dashboard's HTTP parser rejects - HPE_INVALID_CONSTANT,
        # about 40 log errors per ten minutes per tile. Every route behaves that
        # way, so no other path helps. ping probes the host with ICMP instead and
        # reads only the host name from this URL, so it reports the host rather
        # than Pi-hole itself; the widget below is what covers the service.
        ping: $(yq "$ph_url")
        widget:
          type: pihole
          url: $(yq "$ph_url")
          version: 6
          key: $(yq "$ph_pw")
YAML
  done
}

homepage_services_yaml() {        # homepage_services_yaml DIR DOMAIN PLEX_TOKEN SEERR_KEY
  local dir=$1 d=$2 plex_token=$3 seerr_key=$4
  {
    echo "# Generated by configure.sh - edits are overwritten on the next run."
    homepage_tiles_media "$d" "$plex_token" "$seerr_key"
    homepage_tiles_recently_added "$d" "$plex_token"
    homepage_tiles_today "$d"
    homepage_tiles_downloads "$d"
    homepage_tiles_automation "$d"
    homepage_tiles_infrastructure
  } > "$dir/services.yaml"
  chmod 600 "$dir/services.yaml"
  ok "services.yaml (API keys inside, mode 600)"
}

homepage_refresh_news() {         # homepage_refresh_news DIR
  local dir=$1 entries
  if [[ -w "$dir/news" || ( ! -e "$dir/news" && -w "$dir" ) ]]; then
    ./news.sh >/dev/null && ok "headlines fetched for: $(tr ';' '\n' <<<"$NEWS_FEEDS" | cut -d'|' -f1 | paste -sd, - | sed 's/,/, /g') (news.sh)"
    # Homepage lists its static files once at start; a feed file that is new
    # since then is 404 until the container restarts (updates to an existing
    # file are served as they are).
    local entry missing=0
    IFS=';' read -ra entries <<<"$NEWS_FEEDS"
    for entry in "${entries[@]}"; do
      docker compose exec -T homepage wget -q -O /dev/null -T 5 "http://localhost:3000/news/$(homepage_news_slug "${entry%%|*}").json" 2>/dev/null || missing=1
    done
    if (( missing )); then
      docker compose restart homepage >/dev/null 2>&1
      ok "Homepage restarted to pick up new feed files"
    fi
    systemctl --user is-enabled media-stack-news.timer >/dev/null 2>&1 || echo "        (install the refresh timer: ./news.sh install)"
  else
    echo "   WARN $dir/news is not writable (created by Docker as root?): sudo chown $USER $dir/news"
  fi
}

configure_homepage() {
  log "Homepage dashboard"
  local dir="$CONFIG_ROOT/homepage" plex_token seerr_key
  plex_token=$(plex_token)
  seerr_key=$(jq -r 'select(.public.initialized == true) | .main.apiKey // empty' "$CONFIG_ROOT/seerr/settings.json" 2>/dev/null || true)

  local recent=no
  [[ -n "$plex_token" ]] && recent=yes
  homepage_settings_yaml "$dir" "$recent" yes
  homepage_widgets_yaml "$dir"
  homepage_docker_yaml "$dir"
  [[ -f "$dir/bookmarks.yaml" ]] || : > "$dir/bookmarks.yaml"
  homepage_services_yaml "$dir" "$SITE_DOMAIN" "$plex_token" "$seerr_key"
  [[ -n "$plex_token" ]] || echo "        (Plex tile gets its widget once the server is claimed)"
  [[ -n "$seerr_key" ]] || echo "        (Seerr tile gets its widget once Seerr's setup is completed)"
  [[ -z "${NEWS_FEEDS:-}" ]] || homepage_refresh_news "$dir"
  if (( LOGIN_CHANGED )); then
    # qBittorrent may have banned Homepage's IP for stale-login attempts made
    # before the stop above took effect; a restart clears the in-memory ban.
    docker compose restart qbittorrent >/dev/null 2>&1
    docker compose start homepage >/dev/null 2>&1
    ok "Homepage restarted with the new login"
  fi
  # The dashboard is a statically generated page: writing the YAML changes
  # nothing a browser can see until the page is rebuilt, and a plain container
  # restart keeps the cached one. Homepage's own endpoint does the rebuild,
  # which is why the tiles show a setting the moment this script sets it.
  if curl -fsS -o /dev/null -m 15 "http://localhost:3000/api/revalidate" 2>/dev/null; then
    ok "dashboard page rebuilt"
  else
    echo "        (could not reach Homepage to rebuild its page; it refreshes by itself within the hour)"
  fi
}
