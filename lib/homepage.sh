homepage_widgets_yaml() {         # homepage_widgets_yaml DIR
  local dir=$1
  if homepage_keep "$dir/widgets.yaml"; then
    skip "widgets.yaml (# keep)"
  else
    {
      # The archive gets its own figure only when the tier is on. It is where
      # things go when /data fills, so the one number that matters during a
      # mover run - is there anywhere left to move to - is invisible without it.
      # archive_enabled, not just the rclone service: without a remote in
      # rclone.conf nothing mounts, and /data/archive/media is then a plain
      # directory that would report the local disk a second time. The path is
        # the mount itself, not data/archive above it: since the union that is an
        # ordinary directory, and watching it gave the local disk two tiles, one
        # of them wearing a cloud.
      if archive_enabled; then
        # One group, two disks, no labels: the second entry is the archive and
        # custom.css swaps its drive glyph for a cloud, which says the same
        # thing without a caption. The widget takes no icon: key of its own -
        # that belongs to services, which is how the Archive tile further down
        # gets its mdi-cloud-lock-outline - so the icon is styled, not set.
        cat <<YAML
# Generated by configure.sh - put "# keep" on this line to make it yours.
- resources:
    cpu: true
    memory: true
    disk:
      - /data
      - /data/archive/media
YAML
      else
        cat <<YAML
# Generated by configure.sh - put "# keep" on this line to make it yours.
- resources:
    cpu: true
    memory: true
    disk: /data
YAML
      fi
      if [[ -n "${WEATHER_LATITUDE:-}" && -n "${WEATHER_LONGITUDE:-}" ]]; then cat <<YAML
- openmeteo:
    label: $(yq "${WEATHER_LABEL:-}")
    latitude: $WEATHER_LATITUDE
    longitude: $WEATHER_LONGITUDE
    timezone: $(yq "${TZ:-UTC}")
    units: metric
    cache: 10
YAML
      fi
      cat <<YAML
- datetime:
    text_size: sm
    locale: $(yq "${UI_LOCALE:-en-US}")
    # Named parts rather than a dateStyle: "za 26 sep, 12:08" keeps the weekday,
    # which is the bit worth a glance, without the year and the spelled-out
    # month that make the full style run the width of the header. A dateStyle of
    # short would fit too, but "26-09-2026, 12:08" reads like a receipt.
    format:
      weekday: short
      day: numeric
      month: short
      hour: 2-digit
      minute: 2-digit
      hour12: $([[ ${UI_TIME_FORMAT:-24h} == 12h ]] && echo true || echo false)
YAML
    } > "$dir/widgets.yaml"
    ok "widgets.yaml${WEATHER_LATITUDE:+ (weather for ${WEATHER_LABEL:-$WEATHER_LATITUDE,$WEATHER_LONGITUDE})}"
  fi
}

