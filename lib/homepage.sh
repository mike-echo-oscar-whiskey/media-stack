homepage_tiles_recently_added() { # homepage_tiles_recently_added DOMAIN PLEX_TOKEN
  local d=$1 plex_token=$2
  # Recently added, straight from Plex's per-library listings (newest first,
  # as JSON). Links open the item
  # in Plex Web.
  if [[ -n "$plex_token" ]]; then
    local machine sections movies_key shows_key
    machine=$(sed -n 's/.*ProcessedMachineIdentifier="\([^"]*\)".*/\1/p' "$PLEX_PREFS")
    sections=$(curl -fsS -m 10 -H "X-Plex-Token: $plex_token" -H 'Accept: application/json' "http://$PLEX_INTERNAL_HOST:32400/library/sections" 2>/dev/null || echo '{}')
    movies_key=$(jq -r '.MediaContainer.Directory[]? | select(.title == "Movies") | .key' <<<"$sections")
    shows_key=$(jq -r '.MediaContainer.Directory[]? | select(.title == "TV Shows") | .key' <<<"$sections")
    if [[ -n "$movies_key" && -n "$shows_key" ]]; then cat <<YAML
- Recently added:
    - Films:
        icon: mdi-movie-open-plus-outline
        href: http://plex.$d/web/index.html#!/media/$machine/com.plexapp.plugins.library?source=$movies_key
        widget:
          type: customapi
          url: $(yq "http://$PLEX_INTERNAL_HOST:32400/library/sections/$movies_key/all?type=1&sort=addedAt:desc&X-Plex-Container-Start=0&X-Plex-Container-Size=8")
          headers:
            Accept: application/json
            X-Plex-Token: $(yq "$plex_token")
          refreshInterval: 300000
          display: dynamic-list
          mappings:
            items: MediaContainer.Metadata
            name: title
            label: year
            limit: 8
            target: $(yq "http://plex.$d/web/index.html#!/server/$machine/details?key=%2Flibrary%2Fmetadata%2F{ratingKey}")
    - Series:
        icon: mdi-television-play
        href: http://plex.$d/web/index.html#!/media/$machine/com.plexapp.plugins.library?source=$shows_key
        widget:
          type: customapi
          url: $(yq "http://$PLEX_INTERNAL_HOST:32400/library/sections/$shows_key/all?type=3&sort=addedAt:desc&X-Plex-Container-Start=0&X-Plex-Container-Size=8")
          headers:
            Accept: application/json
            X-Plex-Token: $(yq "$plex_token")
          refreshInterval: 300000
          display: dynamic-list
          mappings:
            items: MediaContainer.Metadata
            name: parentTitle
            label: title
            limit: 8
            target: $(yq "http://plex.$d/web/index.html#!/server/$machine/details?key=%2Flibrary%2Fmetadata%2F{ratingKey}")
YAML
    fi
  fi
}

homepage_tiles_today() {          # homepage_tiles_today DOMAIN
  local d=$1 entries
  cat <<YAML
- Today:
    - Upcoming series:
        icon: mdi-television-classic
        widget:
          type: calendar
          view: agenda
          maxEvents: 10
          showTime: true
          integrations:
            - type: sonarr
              service_group: Automation
              service_name: Sonarr
              baseUrl: http://sonarr.$d
    - Upcoming films:
        icon: mdi-movie-open-outline
        widget:
          type: calendar
          view: agenda
          maxEvents: 10
          showTime: true
          integrations:
            - type: radarr
              service_group: Automation
              service_name: Radarr
              baseUrl: http://radarr.$d
YAML
  local entry title url
  IFS=';' read -ra entries <<<"${NEWS_FEEDS:-}"
  for entry in "${entries[@]}"; do
    title=${entry%%|*}; url=${entry#*|}
    [[ -n "$title" && "$url" == http* ]] || continue
    url=${url%% *}                    # several sources: the tile links to the first
    cat <<YAML
    - $(yq "$title"):
        icon: mdi-newspaper-variant-outline
        href: $(yq "${url%%/feed*}")
        widget:
          type: customapi
          url: http://localhost:3000/news/$(homepage_news_slug "$title").json
          refreshInterval: 300000
          display: dynamic-list
          mappings:
            items: items
            name: title
            label: published
            format: relativeDate
            limit: 8
            target: "{link}"
YAML
  done
}

